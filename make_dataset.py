# synthetic SL telecom churn data (operators / districts / LKR bills)
import numpy as np
import pandas as pd
from pathlib import Path

RNG = np.random.default_rng(42)

OPERATORS = ["Dialog", "Mobitel", "Hutch", "Airtel"]
DISTRICTS = [
    "Colombo", "Gampaha", "Kandy", "Galle", "Jaffna", "Kurunegala",
    "Kalutara", "Matara", "Anuradhapura", "Ratnapura", "Negombo", "Batticaloa",
]
PLAN_TYPES = ["Prepaid", "Postpaid", "Broadband", "Combo"]
PAYMENT = ["Cash", "Card", "eZ Cash", "Bank transfer"]
COMPLAINTS = ["No complaint", "Network", "Billing", "Customer care", "Speed"]


def _make_row():
    operator = RNG.choice(OPERATORS, p=[0.38, 0.32, 0.18, 0.12])
    district = RNG.choice(DISTRICTS)
    plan = RNG.choice(PLAN_TYPES, p=[0.45, 0.25, 0.15, 0.15])
    tenure = int(RNG.integers(1, 72))
    monthly_bill = float(np.round(RNG.uniform(350, 6500), 2))
    data_gb = float(np.round(RNG.uniform(0.5, 120), 1))
    calls_min = int(RNG.integers(20, 1800))
    late_payments = int(RNG.integers(0, 8))
    avg_speed = float(np.round(RNG.uniform(2, 85), 1))
    nights_active = int(RNG.integers(0, 31))
    complaint = RNG.choice(COMPLAINTS, p=[0.55, 0.18, 0.12, 0.08, 0.07])
    payment = RNG.choice(PAYMENT, p=[0.25, 0.35, 0.28, 0.12])
    age = int(RNG.integers(18, 68))
    is_urban = 1 if district in {"Colombo", "Gampaha", "Kandy", "Galle", "Negombo"} else 0

    # rough churn signal – higher bill + short tenure + complaints etc.
    # baseline kept negative so overall churn sits ~25-35% (more realistic)
    score = -2.4
    score += 1.1 if tenure < 6 else (-0.55 if tenure > 24 else 0)
    score += 0.85 if monthly_bill > 3500 else 0
    score += 0.45 * late_payments
    score += 0.95 if complaint in {"Network", "Billing", "Speed"} else -0.45
    score += 0.55 if avg_speed < 10 else (-0.3 if avg_speed > 40 else 0)
    score += 0.4 if plan == "Prepaid" and monthly_bill > 2500 else 0
    score += 0.3 if operator in {"Hutch", "Airtel"} and is_urban == 0 else 0
    score += RNG.normal(0, 0.9)

    p = 1 / (1 + np.exp(-score))
    churned = int(RNG.random() < p)

    return {
        "customer_id": None,  # filled later
        "operator": operator,
        "district": district,
        "plan_type": plan,
        "tenure_months": tenure,
        "monthly_bill_lkr": monthly_bill,
        "data_usage_gb": data_gb,
        "call_minutes": calls_min,
        "late_payments_6m": late_payments,
        "avg_download_mbps": avg_speed,
        "active_nights_last_month": nights_active,
        "last_complaint": complaint,
        "payment_method": payment,
        "age": age,
        "urban": is_urban,
        "churned": churned,
    }


def build(n=8000):
    rows = [_make_row() for _ in range(n)]
    df = pd.DataFrame(rows)
    df["customer_id"] = [f"SL-{i:05d}" for i in range(1, n + 1)]
    # shuffle so it doesn't look sequentially generated by class
    df = df.sample(frac=1, random_state=7).reset_index(drop=True)
    return df


if __name__ == "__main__":
    out = Path(__file__).parent / "data" / "sl_telecom_churn.csv"
    out.parent.mkdir(parents=True, exist_ok=True)
    df = build()
    df.to_csv(out, index=False)
    print(f"wrote {out}  shape={df.shape}  churn_rate={df.churned.mean():.3f}")
